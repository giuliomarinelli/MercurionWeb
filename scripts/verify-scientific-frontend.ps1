# Mercurion scientific Notebook v1 — Windows PowerShell 7 validation.
# No manual edits to generated types, and no PostgreSQL mutations.
param(
    [switch]$SkipBuild,
    [switch]$RunTests
)

$ErrorActionPreference = 'Stop'
Set-StrictMode -Version Latest

$repoRoot = Split-Path -Parent $PSScriptRoot
$frontendRoot = Join-Path $repoRoot 'MercurionWebNg'
$schema = Join-Path $repoRoot 'MercurionWebNode/src/schema.graphql'
if (-not (Test-Path $schema)) {
    throw 'Committed Nest GraphQL schema not found: MercurionWebNode/src/schema.graphql'
}
if (-not (Test-Path (Join-Path $frontendRoot 'package.json'))) {
    throw 'MercurionWebNg/package.json not found'
}

function Run-Required {
    param([string]$Description, [string[]]$Arguments)
    Write-Host ''
    Write-Host ">>> $Description" -ForegroundColor Cyan
    & npm.cmd @Arguments
    if ($LASTEXITCODE -ne 0) {
        throw "$Description failed (exit code $LASTEXITCODE)"
    }
}

Push-Location $frontendRoot
try {
    Run-Required 'Validate static GraphQL documents against Nest SDL' @('run', 'graphql:validate')
    Run-Required 'Regenerate Angular typed GraphQL artifacts (source generated by tooling)' @(
        'run', 'graphql:generate'
    )
    Run-Required 'GraphQL catalog/codegen drift and negative tests' @('run', 'graphql:check')
    Run-Required 'Angular TypeScript application check' @('run', 'typecheck')
    Run-Required 'Angular lint' @('run', 'lint')
    if (-not $SkipBuild) {
        Run-Required 'Angular production build' @('run', 'build')
    }
    if ($RunTests) {
        # Opt-in Karma browser tests; requires an available Chrome/Chromium.
        Run-Required 'Notebook-focused Angular component tests' @(
            'run', 'test', '--', '--watch=false',
            '--include=src/app/services/graphql/notebook.service.spec.ts',
            '--include=src/app/components/notebook/notebook-tree/notebook-tree.component.spec.ts',
            '--include=src/app/components/notebook/notebook-tree-index/notebook-toc.component.spec.ts',
            '--include=src/app/pages/notebook/notebook-landing/notebook-landing.component.spec.ts',
            '--include=src/app/pages/notebook/edit/edit.page.component.spec.ts'
        )
    }
    Write-Host ''
    Write-Host 'Scientific frontend validations passed.' -ForegroundColor Green
    Write-Host 'Review generated/schema.ts, generated/graphql.ts and git status; commit generated changes.' -ForegroundColor Yellow
} finally {
    Pop-Location
}
